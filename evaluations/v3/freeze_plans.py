"""Phase 7: freeze ONE validated plan per benchmark question before the V3 evaluation (offline, no API calls).

Each plan is the V2 repetition-1 plan, regenerated by replaying its RECORDED planner response through the
unchanged planner code (pathfinder.planner), so no new provider call is made. The plan file records its
provenance (source store and its SHA-256, the request key, the plan hash) and the validation checks.
V3 `evaluate --plans-dir evaluations/v3/plans` reuses each plan for every repetition and every arm.

Usage: python evaluations/v3/freeze_plans.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from pathfinder.config import load_settings
from pathfinder.evaluation import freeze_plan, load_queries, plan_hash
from pathfinder.models import Mode, ResearchPlan
from pathfinder.replay import RecordingLLM, SnapshotStore
from pathfinder.scoring import parse_weights

ROOT = Path(__file__).resolve().parents[2]
V2_FINGERPRINT = "b891d16fe6"
OUT = ROOT / "evaluations" / "v3" / "plans"


def validate(plan: ResearchPlan, expected_mode: str) -> list[str]:
    """Checks a frozen plan must pass; returns the list of checks (raises on failure)."""
    checks = []

    def need(ok: bool, msg: str) -> None:
        if not ok:
            raise ValueError(f"plan validation failed: {msg}")
        checks.append(msg)

    need(plan.mode.value == expected_mode, f"mode is {expected_mode} as in queries.json")
    if plan.mode == Mode.COMPARISON:
        need(len(plan.alternatives) >= 2, f"{len(plan.alternatives)} alternatives (>= 2)")
        need(2 <= len(plan.criteria) <= 5, f"{len(plan.criteria)} criteria (2-5)")
        need(len({c.criterion_id for c in plan.criteria}) == len(plan.criteria), "unique criterion ids")
        need(all(1 <= c.weight <= 5 for c in plan.criteria), "weights within 1-5")
        need(all(c.anchors.poor and c.anchors.plausible and c.anchors.strong for c in plan.criteria),
             "every criterion has 0/1/2 rubric anchors")
        need(all(c.preferred_scope is None or c.preferred_scope in c.scopes for c in plan.criteria),
             "preferred scopes are declared scopes")
    else:
        need(len(plan.facets) >= 1, f"{len(plan.facets)} facets (>= 1)")
        need(plan.target_entity_count >= 0, f"target entity count {plan.target_entity_count}")
    need(len(plan.initial_queries) >= 1, f"{len(plan.initial_queries)} initial queries")
    return checks


def main() -> None:
    settings = load_settings()
    OUT.mkdir(parents=True, exist_ok=True)
    summary = ["# Frozen V3 plans", "",
               "One plan per question, reused for every repetition and arm. Regenerated offline from the "
               "recorded V2 repetition-1 planner response (no new provider call).", "",
               "| Q | mode | alternatives / facets | criteria | cells or units | plan hash |", "|---|---|---|---|---|---|"]
    for q in load_queries(ROOT / "evaluations" / "queries.json"):
        if not q.get("required"):
            continue
        store_path = ROOT / "evaluations" / "snapshots" / q["id"] / V2_FINGERPRINT / "plan_rep1.json"
        llm = RecordingLLM(None, SnapshotStore(store_path), "replay", settings.llm_model)
        plan = freeze_plan(llm, settings, q["question"], parse_weights(q.get("weights")))
        checks = validate(plan, q["mode"])
        prov = {"source_store": str(store_path.relative_to(ROOT)).replace("\\", "/"),
                "source_store_sha256": hashlib.sha256(store_path.read_bytes()).hexdigest(),
                "regenerated_with": "pathfinder.planner (unchanged since V2) in replay mode",
                "plan_hash": plan_hash(plan), "question": q["question"]}
        (OUT / f"{q['id']}.json").write_text(json.dumps({"plan": plan.model_dump(mode="json"), "provenance": prov,
                                                         "validation": checks}, indent=2), encoding="utf-8")
        if plan.mode == Mode.COMPARISON:
            row = (f"| {q['id']} | comparison | {', '.join(a.name for a in plan.alternatives)} | "
                   f"{', '.join(f'{c.criterion_id} (w{c.weight})' for c in plan.criteria)} | "
                   f"{len(plan.alternatives) * len(plan.criteria)} | `{prov['plan_hash']}` |")
        else:
            row = (f"| {q['id']} | discovery | {', '.join(f.facet_id for f in plan.facets)} | - | "
                   f"{plan.target_entity_count or sum(f.required_count for f in plan.facets)} | `{prov['plan_hash']}` |")
        summary.append(row)
        print(row)
    (OUT / "PLANS.md").write_text("\n".join(summary) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
